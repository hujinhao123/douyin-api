def build_query(params: dict[str, Any] | None = None, common: dict[str, Any] | None = None) -> dict[str, Any]:
    """Merge caller params over the common parameter set, dropping empty values."""
    base = dict(COMMON_PARAMS if common is None else common)
    for key, value in (params or {}).items():
        if value is None or value == "":
            continue
        base[key] = value
    return {k: v for k, v in base.items() if v is not None and v != ""}
